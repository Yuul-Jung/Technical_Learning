//============================================================
// 파일명: c_halfadder.v
// 목적  : 1bit Half Adder 회로 작성
// 설명  :
//   - 입력 in_a, in_b를 더함
//   - sum은 합 출력임
//   - carry는 자리올림 출력임
//============================================================

module c_halfadder(
    input  in_a,
    input  in_b,
    output sum,
    output carry
);

//------------------------------------------------------------
// XOR 연산
// 입력이 서로 다르면 1 출력
//------------------------------------------------------------
assign sum = in_a ^ in_b;

//------------------------------------------------------------
// AND 연산
// 입력이 모두 1이면 1 출력
//------------------------------------------------------------
assign carry = in_a & in_b;

endmodule
